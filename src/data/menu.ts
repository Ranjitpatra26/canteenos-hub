export const menuItems: MenuItem[] = raw.map((item, i) => ({
  ...item,
  id: `m${i + 1}`,
  slug: item.name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, ""),
}));

export const getMenuItem = (id: string) => menuItems.find((m) => m.id === id);
export const getMenuItemBySlug = (slug: string) => menuItems.find((m) => m.slug === slug);
export const getCategory = (slug: string) => categories.find((c) => c.slug === slug);
