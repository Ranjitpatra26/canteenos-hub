const pick = (idx: number) => menuItems[idx % menuItems.length];

function build(
  n: number,
  status: Order["status"],
  minutesAgo: number,
  customerIdx: number,
  itemIdxs: number[],
  method: Order["method"],
): Order {
  const lines = itemIdxs.map((i, k) => {
    const m = pick(i);
    return { itemId: m.id, name: m.name, qty: (k % 2) + 1, price: m.price, emoji: m.emoji };
  });
  const subtotal = lines.reduce((s, l) => s + l.price * l.qty, 0);
  const gst = Math.round(subtotal * 0.05);
  const fee = method === "delivery" ? 20 : 0;
  const c = customers[customerIdx % customers.length];
  const placedAt = new Date(Date.now() - minutesAgo * 60_000).toISOString();
  return {
    id: `o${n}`,
    code: `CO-${8400 + n}`,
    customerId: c.id,
    customerName: c.name,
    customerAvatarTint: c.tint,
    placedAt,
    status,
    method,
    counter:
      method === "pickup" ? `Counter ${(n % 4) + 1}` : `Block ${String.fromCharCode(65 + (n % 4))}`,
    lines,
    subtotal,
    gst,
    fee,
    total: subtotal + gst + fee,
    etaMins: 8 + (n % 5) * 3,
    paymentMethod: ["Campus Wallet", "UPI", "Card", "Meal Plan"][n % 4],
  };
}

